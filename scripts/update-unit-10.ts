// Merge Russian data
rawLessons.forEach((lesson: any, i: number) => {
  const ru = unit10Ru[i];
  if (!ru) throw new Error(`Missing Russian data for unit 10 lesson ${i}`);

  lesson.topicRu = ru.topicRu;

  lesson.words.forEach((w: any, wIdx: number) => {
    w.russian = ru.phrasesRu[wIdx];
  });

  lesson.voices.forEach((v: any, vIdx: number) => {
    v.promptRu = "Как сказать по-английски:";
    v.targetRussian = ru.speakRu[vIdx];
  });

  lesson.sentences.forEach((s: any, sIdx: number) => {
    s.russian = ru.sentenceRu[sIdx];
  });

  lesson.fillBlanks.forEach((fb: any, fbIdx: number) => {
    const fbRu = ru.fillsRu[fbIdx];
    fb.russianHint = fbRu.russianHint;
    const [b = "", a = ""] = fbRu.ruBlank.sentence.split("___");
    fb.russianParts = [b, a];
    fb.russianAnswer = fbRu.ruBlank.answer;
    fb.russianWrongs = fbRu.ruBlank.wrongs;
  });

  lesson.conversations.forEach((c: any, cIdx: number) => {
    const cRu = ru.convosRu[cIdx];
    c.situationRu = cRu.situationRu;
    c.theyAskRu = cRu.theyAskRu;
    c.correctRu = cRu.correctRu;
    c.wrong1Ru = cRu.wrong1Ru;
    c.wrong2Ru = cRu.wrong2Ru;
    c.wrong3Ru = cRu.wrong3Ru;
    c.explanationRu = cRu.explanationRu;
  });
});

